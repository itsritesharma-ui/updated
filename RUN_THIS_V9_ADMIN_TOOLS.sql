-- ---------- Support tickets ----------
create table if not exists public.support_tickets (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  customer_name text not null,
  customer_email text not null,
  category text not null check(category in ('payment','book_access','technical','account','refund','other')),
  subject text not null check(length(subject) between 3 and 140),
  related_order_id text,
  status text not null default 'open' check(status in ('open','in_progress','waiting_customer','resolved','closed')),
  priority text not null default 'medium' check(priority in ('low','medium','high')),
