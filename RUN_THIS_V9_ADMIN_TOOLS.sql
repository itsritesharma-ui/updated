create function public.customer_reply_to_support_ticket(target_ticket uuid, reply_body text, reply_attachments jsonb default '[]'::jsonb)
returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare message_id uuid;
begin
  if length(trim(coalesce(reply_body,''))) < 1 or length(reply_body) > 10000 then
    raise exception 'Reply must be between 1 and 10000 characters';
  end if;
  if jsonb_typeof(coalesce(reply_attachments,'[]'::jsonb)) <> 'array' then
    raise exception 'Attachments must be a JSON array';
  end if;
  if not exists(select 1 from public.support_tickets where id=target_ticket and user_id=auth.uid()) then
    raise exception 'Ticket not found or not authorized';
  end if;
  insert into public.support_messages(ticket_id,sender_id,sender_role,body,internal,attachments)
  values(target_ticket,auth.uid(),'customer',trim(reply_body),false,coalesce(reply_attachments,'[]'::jsonb))
  returning id into message_id;
  update public.support_tickets set status='open',updated_at=now() where id=target_ticket;
  return message_id;
end;
$$;
revoke all on function public.customer_reply_to_support_ticket(uuid,text,jsonb) from public;
grant execute on function public.customer_reply_to_support_ticket(uuid,text,jsonb) to authenticated;

create or replace function public.customer_mark_support_tickets_read(target_ticket uuid default null)
returns integer
language plpgsql
security definer
set search_path=public
as $$
declare changed integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  update public.support_tickets
  set customer_unread_count=0
  where user_id=auth.uid() and customer_unread_count > 0 and (target_ticket is null or id=target_ticket);
  get diagnostics changed = row_count;
  return changed;
end;
$$;
revoke all on function public.customer_mark_support_tickets_read(uuid) from public;
grant execute on function public.customer_mark_support_tickets_read(uuid) to authenticated;

create or replace function public.admin_update_support_ticket(
  target_ticket uuid,
  new_status text,
  new_priority text,
  reply_body text default '',
  make_internal boolean default false,
  reply_attachments jsonb default '[]'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare
  message_id uuid;
  clean_body text := trim(coalesce(reply_body,''));
begin
  if not public.is_admin() then raise exception 'Not authorized'; end if;
  if new_status not in ('open','in_progress','waiting_customer','resolved','closed') then raise exception 'Invalid ticket status'; end if;
  if new_priority not in ('low','medium','high') then raise exception 'Invalid ticket priority'; end if;
  if length(clean_body) > 10000 then raise exception 'Reply must be 10000 characters or fewer'; end if;
  if jsonb_typeof(coalesce(reply_attachments,'[]'::jsonb)) <> 'array' then raise exception 'Attachments must be a JSON array'; end if;
  if clean_body='' and jsonb_array_length(coalesce(reply_attachments,'[]'::jsonb)) > 0 then clean_body := 'Attachment added.'; end if;

  update public.support_tickets
  set status=new_status,
      priority=new_priority,
      admin_unread_count=0,
      customer_unread_count=customer_unread_count + case when status<>new_status and (clean_body='' or make_internal) then 1 else 0 end,
      updated_at=now()
  where id=target_ticket;
  if not found then raise exception 'Ticket not found'; end if;

  if clean_body <> '' then
    insert into public.support_messages(ticket_id,sender_id,sender_role,body,internal,attachments)
    values(target_ticket,auth.uid(),'admin',clean_body,make_internal,coalesce(reply_attachments,'[]'::jsonb))
    returning id into message_id;
  end if;
  return message_id;
end;
$$;
revoke all on function public.admin_update_support_ticket(uuid,text,text,text,boolean,jsonb) from public;
grant execute on function public.admin_update_support_ticket(uuid,text,text,text,boolean,jsonb) to authenticated;

create or replace function public.touch_support_ticket()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  update public.support_tickets
  set updated_at=now(),
      admin_unread_count=admin_unread_count + case when new.sender_role='customer' and not new.internal then 1 else 0 end,
      customer_unread_count=customer_unread_count + case when new.sender_role='admin' and not new.internal then 1 else 0 end,
      last_admin_reply_at=case when new.sender_role='admin' and not new.internal then now() else last_admin_reply_at end
  where id=new.ticket_id;
  return new;
end;
$$;
drop trigger if exists support_message_touch_ticket on public.support_messages;
create trigger support_message_touch_ticket after insert on public.support_messages
for each row execute function public.touch_support_ticket();

