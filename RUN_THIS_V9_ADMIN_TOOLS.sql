create or replace function public.create_support_ticket(
  ticket_customer_name text,
  ticket_customer_email text,
  ticket_category text,
  ticket_subject text,
  ticket_related_order text,
  initial_body text
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  new_ticket public.support_tickets;
  account_email text;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if length(trim(coalesce(ticket_customer_name,''))) < 2 or length(ticket_customer_name) > 120 then
    raise exception 'Customer name must be between 2 and 120 characters';
  end if;
  if length(trim(coalesce(ticket_subject,''))) < 3 or length(ticket_subject) > 140 then
    raise exception 'Subject must be between 3 and 140 characters';
  end if;
  if length(trim(coalesce(initial_body,''))) < 1 or length(initial_body) > 10000 then
    raise exception 'Message must be between 1 and 10000 characters';
  end if;
  select email into account_email from auth.users where id=auth.uid();
  insert into public.support_tickets(user_id,customer_name,customer_email,category,subject,related_order_id)
  values(auth.uid(),trim(ticket_customer_name),coalesce(account_email,trim(ticket_customer_email)),ticket_category,trim(ticket_subject),nullif(trim(ticket_related_order),''))
  returning * into new_ticket;
  insert into public.support_messages(ticket_id,sender_id,sender_role,body,internal)
  values(new_ticket.id,auth.uid(),'customer',trim(initial_body),false);
  return jsonb_build_object('id',new_ticket.id,'ticket_number',new_ticket.ticket_number);
end;
$$;
revoke all on function public.create_support_ticket(text,text,text,text,text,text) from public;
grant execute on function public.create_support_ticket(text,text,text,text,text,text) to authenticated;

drop function if exists public.customer_reply_to_support_ticket(uuid,text);
